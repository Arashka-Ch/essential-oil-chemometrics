    pdf.set_font("Arial", 'I', 10)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 10, "Automated Chemometric AI Quality Control", ln=True, align='C')
    pdf.ln(10)
    
    # Batch Info
    pdf.set_font("Arial", 'B', 12)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(50, 10, "Batch Reference:", border=1)
    pdf.set_font("Arial", '', 12)
