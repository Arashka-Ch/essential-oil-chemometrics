# --- Synthetic Data Generation ---
@st.cache_data
def generate_gcms_data():
    np.random.seed(42)
    terpenes = ['Linalool', 'Geraniol', 'Limonene', 'Carvacrol', 'Thymol', 'a-Pinene', 'b-Pinene', 'Eucalyptol', 'Camphor', 'Terpinen-4-ol']
    data, labels = [], []
    
    for _ in range(60): 
        data.append(np.random.normal(loc=[40, 30, 5, 2, 1, 10, 8, 2, 1, 1], scale=2))
        labels.append("Origin A (Authentic)")
        
    for _ in range(60): 
        data.append(np.random.normal(loc=[10, 15, 35, 1, 1, 20, 15, 1, 1, 1], scale=2))
        labels.append("Origin B (Authentic)")
        
    for _ in range(25): 
        data.append(np.random.normal(loc=[80, 5, 5, 1, 1, 2, 2, 2, 0.5, 0.5], scale=5))
        labels.append("Adulterated (Rejected)")
        
    df = pd.DataFrame(data, columns=terpenes)
    df = np.clip(df, 0.001, None) 
    df = df.replace([np.inf, -np.inf], np.nan).fillna(0.001)
    df['Batch_Class'] = labels
    df.insert(0, 'Batch_ID', [f"BATCH-{i:04d}" for i in range(len(df))])
    return df, terpenes

