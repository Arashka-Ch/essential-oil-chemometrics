# --- Mathematical VIP Extraction ---
def calculate_vips(model):
    t = np.nan_to_num(model.x_scores_)
    w = np.nan_to_num(model.x_weights_)
    q = np.nan_to_num(model.y_loadings_)
    p, h = w.shape
    vips = np.zeros((p,))
    s = np.diag(t.T @ t) * np.diag(q.T @ q) 
    total_s = np.sum(s) if np.sum(s) > 1e-10 else 1e-10 
    
    for i in range(p):
        weight = np.array([ (w[i,j] / (np.linalg.norm(w[:,j]) + 1e-10))**2 for j in range(h) ])
        vips[i] = np.sqrt(p * (s @ weight) / total_s)
    return np.nan_to_num(vips)

# --- PDF Certificate of Analysis Generator ---
def create_coa_pdf(batch_id, status, is_anomalous, profile_dict):
    pdf = FPDF()
    pdf.add_page()
    
    # Header
    pdf.set_font("Arial", 'B', 18)
