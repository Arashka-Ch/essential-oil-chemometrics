    pdf.set_font("Arial", 'B', 12)
    pdf.set_text_color(0, 150, 0) if "Authentic" in status else pdf.set_text_color(200, 0, 0)
    pdf.cell(0, 10, f" {status}", border=1, ln=True)
    
    pdf.set_font("Arial", 'B', 12)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(50, 10, "Anomaly Status:", border=1)
    pdf.set_font("Arial", 'B', 12)
    pdf.set_text_color(200, 0, 0) if is_anomalous else pdf.set_text_color(0, 150, 0)
    pdf.cell(0, 10, " FLAGGED (Isolation Forest)" if is_anomalous else " PASS (Baseline)", border=1, ln=True)
    pdf.ln(10)
    
    # Phytochemical Profile
    pdf.set_font("Arial", 'B', 14)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(0, 10, "Phytochemical Integration Profile", ln=True)
    pdf.set_font("Arial", 'B', 10)
    pdf.cell(100, 8, "Terpene / Biomarker", border=1)
    pdf.cell(0, 8, "Relative Peak Area (mAU)", border=1, ln=True)
    
    pdf.set_font("Arial", '', 10)
